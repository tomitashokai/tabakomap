-- 公式ラインナップに存在しない BAT 銘柄を削除し、合成名だった1件を実在名に寄せる。
--
-- brands-seed.json は実在 SKU の一覧ではなく生成された概算だったため、
-- メーカーのカタログに無い銘柄が混ざっていた。BAT 分を公式と突き合わせた結果:
--
--   ネオ・テリック・タバコ           「テリック」という銘柄は存在しない
--                                    （glo の終売銘柄54種の一覧にも無い）
--   ネオ・フレッシュ・ミックス       実在したのは「ネオ・フレッシュ・メンソール」
--                                    （のち「チルド・メンソール」に改名）。この名前は無い
--   ラッキー・ストライク・フォー・グロー・タバコ・ロースト
--                                    「ロースト」味は無い
--   ペル・メル・ケイエス・ブラック   BAT ジャパンの紙巻きは KENT・KOOL・
--                                    LUCKY STRIKE の3ブランドのみ（batj.com）
--
-- ケント・ネオスティック・トゥルー・タバコ は「ネオスティック」（glo pro 用の細い
-- スティックの呼称）と「トゥルー・タバコ」（glo hyper 用の銘柄）を混ぜた合成名だった。
-- 実在するのは後者なので、旧名の行を消して import-brands.mjs が
-- 「ケント・トゥルー・タバコ（glo hyper用）」として入れ直す。
--
-- 残した BAT 3件（ケント・エス・シリーズ・ワン・100s / クール・マイルド /
-- ラッキー・ストライク・エキスパートカット）は**実在する**。シード名がサイズ抜きの
-- 総称になっているだけなので消さない。
--
-- brands を参照している外部キーは無い（checkins・favorites は spots を見ている）。

delete from public.brands
where name in (
  'ネオ・テリック・タバコ（glo用）',
  'ネオ・フレッシュ・ミックス（glo用）',
  'ラッキー・ストライク・フォー・グロー・タバコ・ロースト',
  'ペル・メル・ケイエス・ブラック',
  'ケント・ネオスティック・トゥルー・タバコ（glo用）'
);
